using System.Collections.Generic;
using System.Linq;
using System.Text;
using Cocoar.SignalARRR.SourceGenerator.Model;

namespace Cocoar.SignalARRR.SourceGenerator.Emitters;

/// <summary>
/// Emits the receiving side of a contract: a dispatcher that maps an incoming method name and
/// argument count to a direct, statically typed call on the implementation. It replaces the
/// reflection-based dispatch (<c>GetInterfaceMap</c>, <c>MethodInfo.Invoke</c>,
/// <c>MakeGenericMethod</c>) the .NET clients used, which NativeAOT cannot run.
/// </summary>
/// <remarks>
/// The rules mirror what the reflection registry enforced: a member the contract declares itself
/// hides every inherited member of the same wire name, and two members reachable under the same
/// name with an overlapping argument count are indistinguishable on the wire. That, and generic
/// methods (whose type argument only arrives as a name), make a contract unreceivable; the
/// dispatcher then reports why, and registering it on a client fails with that text.
/// </remarks>
internal static class DispatcherEmitter {
    private const string Runtime = "global::Cocoar.SignalARRR.ProxyGenerator";

    private readonly struct Candidate {
        public Candidate(ContractMethodInfo method) {
            Method = method;
            Total = method.Parameters.Length;
            var required = 0;
            for (var i = 0; i < method.Parameters.Length; i++) {
                if (!method.Parameters[i].HasDefaultValue) required = i + 1;
            }
            Required = required;
        }

        public ContractMethodInfo Method { get; }
        public int Required { get; }
        public int Total { get; }
        public bool Overlaps(Candidate other) => Required <= other.Total && other.Required <= Total;
    }

    public static string Emit(ContractInterfaceInfo info) {
        var problems = new List<string>();
        var groups = new List<(string WireName, List<Candidate> Candidates)>();
        var wireTypes = new List<string>();

        foreach (var group in info.Methods.GroupBy(m => m.WireName)) {
            var methods = group.ToList();
            var generic = methods.Where(m => m.TypeParameterNames.Length > 0).ToList();
            foreach (var m in generic) {
                problems.Add($"its generic method '{m.Name}<{string.Join(", ", m.TypeParameterNames)}>' gets its type argument as a name, which only reflection can turn into a call");
            }

            var candidates = methods.Where(m => m.TypeParameterNames.Length == 0).ToList();
            if (candidates.Any(m => !m.IsInherited)) {
                candidates = candidates.Where(m => !m.IsInherited).ToList();
            }

            var accepted = new List<Candidate>();
            foreach (var method in candidates) {
                var candidate = new Candidate(method);
                var clash = accepted.FirstOrDefault(a => a.Overlaps(candidate));
                if (clash.Method.Name != null) {
                    problems.Add($"'{clash.Method.Name}' and '{method.Name}' are both reachable as '{group.Key}' with the same argument count, and the wire carries no parameter types");
                    continue;
                }

                accepted.Add(candidate);
                CollectWireTypes(method, wireTypes);
            }

            if (accepted.Count > 0) groups.Add((group.Key, accepted));
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CS1998 // Methods without Task or Stream arguments complete synchronously.");
        sb.AppendLine();
        sb.AppendLine($"namespace {info.Namespace}.SignalARRR");
        sb.AppendLine("{");
        sb.AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        sb.AppendLine($"    internal sealed class {info.DispatcherClassName} : {Runtime}.ContractDispatcher<global::{info.FullName}>");
        sb.AppendLine("    {");
        sb.AppendLine($"        public override string WireName => {Literal(info.WireName)};");
        sb.AppendLine();
        sb.AppendLine("        public override global::System.Collections.Generic.IReadOnlyList<global::System.Type> WireTypes { get; } = new global::System.Type[]");
        sb.AppendLine("        {");
        foreach (var type in wireTypes.Distinct()) {
            sb.AppendLine($"            typeof({type}),");
        }
        sb.AppendLine("        };");

        if (problems.Count > 0) {
            var reason = $"'{info.FullName}' cannot be received on a client: " + string.Join("; ", problems) + ".";
            sb.AppendLine();
            sb.AppendLine($"        public override string? UnsupportedReason => {Literal(reason)};");
        }

        sb.AppendLine();
        sb.AppendLine($"        public override async global::System.Threading.Tasks.Task<object?> InvokeAsync(global::{info.FullName} target, string method, {Runtime}.ArgumentReader args)");
        sb.AppendLine("        {");
        // No switch at all for a contract with nothing receivable: an empty one is a compile error.
        if (groups.Count > 0) {
            sb.AppendLine("            switch (method)");
            sb.AppendLine("            {");
        }
        foreach (var (wireName, candidates) in groups) {
            sb.AppendLine($"                case {Literal(wireName)}:");
            foreach (var candidate in candidates) {
                var condition = candidate.Required == candidate.Total
                    ? $"args.Count == {candidate.Total}"
                    : $"args.Count >= {candidate.Required} && args.Count <= {candidate.Total}";
                sb.AppendLine($"                    if ({condition})");
                sb.AppendLine("                    {");
                EmitCall(sb, candidate.Method, "                        ");
                sb.AppendLine("                    }");
            }
            var counts = string.Join(", ", candidates
                .SelectMany(c => Enumerable.Range(c.Required, c.Total - c.Required + 1))
                .OrderBy(c => c));
            sb.AppendLine($"                    throw ArgumentCountMismatch(method, args.Count, {Literal(counts)});");
        }
        if (groups.Count > 0) {
            sb.AppendLine("            }");
            sb.AppendLine();
        }
        sb.AppendLine("            throw MethodNotFound(method);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void CollectWireTypes(ContractMethodInfo method, List<string> wireTypes) {
        foreach (var p in method.Parameters) {
            if (!p.IsCancellationToken && !p.IsStream) wireTypes.Add(p.ClrTypeName);
        }

        switch (method.ReturnCategory) {
            case ReturnTypeCategory.SyncReturn when method.ReturnTypeFullName != "global::System.IO.Stream":
                wireTypes.Add(method.ReturnTypeFullName);
                break;
            case ReturnTypeCategory.TaskOfT when method.ElementTypeFullName != "global::System.IO.Stream":
            case ReturnTypeCategory.AsyncEnumerable:
            case ReturnTypeCategory.ChannelReader:
            case ReturnTypeCategory.Observable:
                wireTypes.Add(method.ElementTypeFullName!);
                break;
        }
    }

    private static void EmitCall(StringBuilder sb, ContractMethodInfo method, string indent) {
        var arguments = string.Join(", ", method.Parameters.Select((p, i) => ArgumentExpression(p, i)));
        // Through the declaring interface: an inherited member is then called exactly, however the
        // contract itself overloads its name.
        var call = $"(({method.DeclaringInterface})target).{method.Name}({arguments})";

        switch (method.ReturnCategory) {
            case ReturnTypeCategory.Void:
                sb.AppendLine($"{indent}{call};");
                sb.AppendLine($"{indent}return null;");
                break;
            case ReturnTypeCategory.Task:
                sb.AppendLine($"{indent}await {call}.ConfigureAwait(false);");
                sb.AppendLine($"{indent}return null;");
                break;
            case ReturnTypeCategory.TaskOfT:
                sb.AppendLine($"{indent}return await {call}.ConfigureAwait(false);");
                break;
            case ReturnTypeCategory.SyncReturn:
                sb.AppendLine($"{indent}return {call};");
                break;
            case ReturnTypeCategory.AsyncEnumerable:
            case ReturnTypeCategory.ChannelReader:
            case ReturnTypeCategory.Observable:
                sb.AppendLine($"{indent}return {Runtime}.StreamingResult.From({call});");
                break;
        }
    }

    private static string ArgumentExpression(ContractParameterInfo parameter, int index) {
        if (parameter.IsCancellationToken) {
            return $"args.ReadCancellationToken({index})";
        }

        if (parameter.IsStream) {
            return $"(await args.ReadStreamAsync({index}).ConfigureAwait(false))!";
        }

        var read = $"args.Read<{parameter.TypeFullName}>({index})";
        return parameter.HasDefaultValue
            ? $"(args.Count > {index} ? {read} : ({parameter.TypeFullName})({parameter.DefaultValueLiteral}))"
            : read;
    }

    private static string Literal(string value) =>
        "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
